// Automatically delete rogue desktop.ini files created by Google Drive / Windows Explorer before resource processing
tasks.matching { it.name.startsWith("merge") || it.name.startsWith("generate") || it.name.startsWith("process") }.configureEach {
    doFirst {
        fileTree(project.file("src/main/res")).matching {
            include("**/desktop.ini", "**/*.ini")
        }.forEach { file ->
            try {
                file.delete()
            } catch (_: Exception) {
            }
        }
    }
}

